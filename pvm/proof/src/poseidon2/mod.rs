    fn m31s<const N: usize>(words: [u32; N]) -> [BaseField; N] {
        words.map(BaseField::from_u32_unchecked)
    }

    /// Plonky3's `test_default_mersenne31_poseidon2_width_16`
    /// (`mersenne-31/src/poseidon2.rs` at `f983316`): the input 0..15 under the
