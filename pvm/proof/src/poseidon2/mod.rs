    /// `rand_xoshiro`'s `Xoroshiro128Plus`, seeded from a `u64` through
    /// `SplitMix64` as its `seed_from_u64` does.
    struct Xoroshiro128Plus([u64; 2]);

    impl Xoroshiro128Plus {
        fn seed_from_u64(seed: u64) -> Self {
            let mut x = seed;
            let mut splitmix = || {
                x = x.wrapping_add(0x9e37_79b9_7f4a_7c15);
                let mut z = x;
                z = (z ^ (z >> 30)).wrapping_mul(0xbf58_476d_1ce4_e5b9);
                z = (z ^ (z >> 27)).wrapping_mul(0x94d0_49bb_1331_11eb);
                z ^ (z >> 31)
            };
            Self([splitmix(), splitmix()])
        }

        fn next_u32(&mut self) -> u32 {
            let [s0, mut s1] = self.0;
            let result = s0.wrapping_add(s1);
            s1 ^= s0;
            self.0 = [s0.rotate_left(24) ^ s1 ^ (s1 << 16), s1.rotate_left(37)];
            (result >> 32) as u32
        }

        /// Plonky3's uniform `Mersenne31`: 31 random bits, P rejected.
        fn m31(&mut self) -> BaseField {
            loop {
                let value = self.next_u32() >> 1;
                if value != P {
                    return BaseField::from_u32_unchecked(value);
                }
            }
        }
    }

