    /// The external block is `[[2, 3, 1, 1], [1, 2, 3, 1], [1, 1, 2, 3],
    /// [3, 1, 1, 2]]`, the internal diagonal `[-2, 2^0, …, 2^8, 2^10, 2^12, …,
    /// 2^16]`, each checked against its matrix on unit vectors.
    #[test]
    fn the_linear_layers_are_plonky3s_matrices() {
        let m4 = [[2, 3, 1, 1], [1, 2, 3, 1], [1, 1, 2, 3], [3, 1, 1, 2]];
        for j in 0..4 {
            let unit: [BaseField; 4] = core::array::from_fn(|i| BaseField::from(u32::from(i == j)));
            let column = apply_m4(unit);
            for i in 0..4 {
                assert_eq!(column[i], BaseField::from(m4[i][j] as u32), "M4[{i}][{j}]");
            }
        }
        // -2 is P - 2.
        let diagonal = [
            0x7fff_fffd,
            1,
            2,
            4,
            8,
            16,
            32,
            64,
            128,
            256,
            1024,
            4096,
            8192,
            16384,
            32768,
            65536,
        ];
        for j in 0..N_STATE {
            let mut unit = [BaseField::zero(); N_STATE];
            unit[j] = BaseField::one();
            apply_internal_round_matrix(&mut unit);
            for (i, &value) in unit.iter().enumerate() {
                let expected = 1 + if i == j { diagonal[i] } else { 0 };
                assert_eq!(value, BaseField::reduce(expected as u64), "M_I[{i}][{j}]");
            }
        }
    }

    /// The sponge a leaf is defined as: the whole row, a one, zeros to a
    /// whole block, absorbed a block at a time.
    fn leaf_hash(row: &[BaseField]) -> P2Hash {
        let mut padded = row.to_vec();
        padded.push(BaseField::one());
        padded.resize(padded.len().next_multiple_of(RATE), BaseField::zero());
        let mut state = [BaseField::zero(); N_STATE];
        for block in padded.chunks_exact(RATE) {
            for (lane, value) in state.iter_mut().zip(block) {
                *lane += *value;
            }
            permute(&mut state);
        }
        P2Hash(state[..8].try_into().unwrap())
    }

    #[test]
    fn a_leaf_hashes_the_same_however_its_row_is_split() {
        let row: Vec<BaseField> = (0..53u32)
            .map(|i| BaseField::from_u32_unchecked(i * 7919 + 1))
            .collect();
        let expected = leaf_hash(&row);
        let splits: [&[usize]; 6] = [
            &[53],
            &[1; 53],
            &[3, 0, 5, 8, 13, 24],
            &[7, 1, 16, 29],
            &[RATE, RATE, RATE, 29],
            &[0, 50, 3],
        ];
        for split in splits {
            let mut hasher = P2MerkleHasher::default();
            let mut rest = row.as_slice();
            for &len in split {
                let (part, tail) = rest.split_at(len);
                hasher.update_leaf(part);
                rest = tail;
            }
            assert!(rest.is_empty());
            assert_eq!(hasher.finalize(), expected, "split {split:?}");
        }
    }
