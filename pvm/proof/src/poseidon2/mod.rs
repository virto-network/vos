//! Poseidon2 over M31, width 16: the permutation, the Merkle hasher and the
//! Fiat-Shamir channel.
//!
//! The recursion verifier-AIR commits inner proofs under an **M31-algebraic**
//! hash so the Merkle-decommit paths are cheap to re-express as constraints,
//! and replays an M31-algebraic Fiat-Shamir transcript so no Blake2s appears on
//! the commit/transcript path. This module holds those primitives — the
//! permutation, the [`MerkleHasherLifted`] commitment hash, and the [`Channel`]
//! transcript — which the formats on the Poseidon2-M31 channel
//! ([`crate::format`]) select at run time.
//!
//! **The channel's encodings are lossless:** a u64 it mixes, and a PoW nonce,
//! enter as four 16-bit limbs and a u32 as two, so no value ≥ p folds onto a
//! smaller one.
//!
//! **The permutation** is the reference Poseidon2 arrangement (eprint 2023/323)
//! with Plonky3's width-16 M31 parameters, as Plonky3 defines them at revision
//! `f98331687e47106a64ab82a77e2e1d0d66c9161b` (`mersenne-31/src/poseidon2.rs`,
//! `poseidon2/src/`):
//! - the S-box `x^5`, 4 + 4 full rounds and 14 partial rounds;
//! - the Grain round constants ([`EXTERNAL_ROUND_CONSTS`],
//!   [`INTERNAL_ROUND_CONSTS`]);
//! - the external matrix `circ(2·M4, M4, M4, M4)` ([`apply_m4`]), applied once
//!   before the first round;
//! - the internal matrix `1 + diag(V)` ([`INTERNAL_DIAGONAL`]).
//!
//! The tests check it against Plonky3's vectors bit for bit.
//!
//! **The prover's hashing** runs sixteen permutations at once on the widest
//! SIMD the build targets ([`packed`]); the scalar [`permute`] is the
//! reference the verifier uses, and the packed code equals it lane for lane.

